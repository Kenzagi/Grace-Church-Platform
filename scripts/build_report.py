def add_heading(text, style, level=0):
    key = "h_%s" % hashlib.md5(text.encode()).hexdigest()[:8]
    p = Paragraph('<a name="%s"/><b>%s</b>' % (key, text), style)
    p.bookmark_name = text
    p.bookmark_level = level
    p.bookmark_text = text
    p.bookmark_key = key
    return p


def major_section(text):
    """H1 + accent underline rule, orphan-protected, never a forced break."""
    return [
        CondPageBreak(H1_ORPHAN),
        Spacer(1, 12),
        KeepTogether([
            add_heading(text, h1, level=0),
            HRFlowable(width="100%", color=ACCENT, thickness=1.4,
                       spaceBefore=2, spaceAfter=12),
        ]),
    ]


def embed_image(path, max_width, max_height):
    pil = PILImage.open(path)
    ow, oh = pil.size
    ratio = min(max_width / ow, max_height / oh, 1.0)
    return Image(path, width=ow * ratio, height=oh * ratio)


def figure_block(path, caption_text, max_width=AVAIL_W, max_height=620):
    img = embed_image(path, max_width, max_height)
    img.hAlign = "CENTER"
    cap = Paragraph(caption_text, caption)
    # Keep the caption glued to its figure whenever the pair can share a page.
    _, cap_h = cap.wrap(AVAIL_W, AVAIL_H)
    _, img_h = img.wrap(AVAIL_W, AVAIL_H)
    if img_h + cap_h + 20 <= AVAIL_H:
        return [Spacer(1, 14), KeepTogether([img, cap]), Spacer(1, 10)]
    return [Spacer(1, 14), img, cap, Spacer(1, 10)]


def data_table(headers, rows, ratios):
    widths = [r * AVAIL_W * 0.98 for r in ratios]
    data = [[Paragraph("<b>%s</b>" % h, tbl_head) for h in headers]]
    for row in rows:
        data.append([Paragraph(c, tbl_cell) for c in row])
    t = Table(data, colWidths=widths, hAlign="CENTER", repeatRows=1)
    style = [
        ("BACKGROUND", (0, 0), (-1, 0), TABLE_HEADER_COLOR),
        ("TEXTCOLOR", (0, 0), (-1, 0), TABLE_HEADER_TEXT),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("GRID", (0, 0), (-1, -1), 0.5, BORDER),
        ("LEFTPADDING", (0, 0), (-1, -1), 7),
        ("RIGHTPADDING", (0, 0), (-1, -1), 7),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ]
    for i in range(1, len(data)):
        style.append(("BACKGROUND", (0, i), (-1, i),
                      TABLE_ROW_ODD if i % 2 else TABLE_ROW_EVEN))
    t.setStyle(TableStyle(style))
    return t


def stat_strip(stats):
    """stats: list of (big, label) -> one-row callout strip."""
    cells = [[Paragraph("<b>%s</b>" % b, stat_big) for b, _ in stats],
             [Paragraph(l, stat_lbl) for _, l in stats]]
    w = AVAIL_W * 0.98 / len(stats)
    t = Table(cells, colWidths=[w] * len(stats), hAlign="CENTER")
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), CARD_BG),
        ("BOX", (0, 0), (-1, -1), 1, ACCENT),
        ("LINEBEFORE", (1, 0), (-1, -1), 0.5, BORDER),
        ("TOPPADDING", (0, 0), (-1, 0), 10),
        ("BOTTOMPADDING", (0, 1), (-1, 1), 10),
        ("TOPPADDING", (0, 1), (-1, 1), 2),
        ("BOTTOMPADDING", (0, 0), (-1, 0), 2),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
    ]))
    return t


